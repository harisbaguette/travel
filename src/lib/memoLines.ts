// 핀 메모를 짧은 한 줄씩으로 쪼갠다.
// 비서는 "에어컨 시원한 실내 · 망고빙수·디저트 — 더위 피하기 좋음, 쿠폰 5% 할인"처럼
// 여러 이야기를 이음표(가운뎃점·줄표·쉼표)로 붙여서 한 문단으로 보낸다. 한 덩어리로 붙어 있으면
// 눈에 잘 안 들어와서, 이음표를 자르는 자리로 삼아 이야기 하나에 한 줄씩 목록으로 만든다.
// 양옆에 빈칸이 있는 이음표만 자른다 — "망고빙수·디저트"처럼 붙어 있는 건 한 낱말이라 그대로 둔다.
export function splitMemoLines(memo: string): string[] {
  return memo
    .split(/\r?\n|\s+[·—–]\s+|,\s+/)
    .map((line) => line.trim().replace(/^[-•·]\s*/, ""))
    .filter(Boolean);
}
